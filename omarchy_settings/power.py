"""Power profile, night light (hyprsunset) and power button (no GTK, testable).

The power profile goes through Omarchy's own command, so the bar shows and remembers the same choice. Night
light talks to hyprsunset like omarchy-toggle-nightlight; its schedule is hyprsunset's own profile file. The
power button is a Hyprland shortcut (logind is told by Omarchy to ignore it), rendered into the generated file.
"""
from __future__ import annotations

import re
import shutil
import time
from pathlib import Path

from . import core

# ------------------------------------------------------------------ power profile
PROFILES = ["power-saver", "balanced", "performance"]


def profiles() -> tuple[list[str], str]:
    """(available profiles in PROFILES order, active one) or ([], "") without power-profiles-daemon."""
    available, active = [], ""
    for line in core.out(["powerprofilesctl", "list"]).splitlines():
        m = re.match(r"^\s*(\*?)\s*([a-z0-9-]+):$", line)
        if m:
            available.append(m.group(2))
            if m.group(1):
                active = m.group(2)
    return [p for p in PROFILES if p in available], active


def set_profile(name: str) -> bool:
    args = (["omarchy-powerprofiles-set", "autodetect", name] if core.have("omarchy-powerprofiles-set")
            else ["powerprofilesctl", "set", name])
    r = core.run(args, timeout=15)
    return bool(r and r.returncode == 0)


# ------------------------------------------------------------------ night light
OFF_TEMP = 6500  # what omarchy-toggle-nightlight uses for "off"
IDENTITY_TEMP = 6000  # below this the screen is tinted
DEFAULT_TEMP = 4000
HYPRSUNSET_CONF = core.CONF_DIR / "hypr" / "hyprsunset.conf"


def temperature() -> int | None:
    """Current hyprsunset temperature, or None when hyprsunset isn't running."""
    m = re.search(r"\d+", core.out(["hyprctl", "hyprsunset", "temperature"]))
    return int(m.group()) if m else None


def nightlight_on(temp: int | None) -> bool:
    return temp is not None and temp < IDENTITY_TEMP


def set_temperature(temp: int) -> bool:
    """Starts hyprsunset if needed and sets the temperature (resent until it sticks, as Omarchy does)."""
    if temperature() is None:
        core.spawn(["uwsm-app", "--", "hyprsunset"])
    for _ in range(15):
        core.run(["hyprctl", "hyprsunset", "temperature", str(temp)])
        time.sleep(0.2)
        if temperature() == temp:
            break
    else:
        return False
    core.run(["omarchy-shell", "-q", "nightlight", "refresh"])
    return True


PROFILE = re.compile(r"^\s*profile\s*\{(.*?)\}", re.S | re.M)


def parse_schedule(text: str) -> tuple[str, str, int] | None:
    """(start, end, temperature) when the file holds exactly an evening profile and a morning identity one."""
    night = day = None
    for body in PROFILE.findall(text):
        fields = dict(re.findall(r"^\s*(\w+)\s*=\s*(\S+)", body, re.M))
        if "time" not in fields:
            continue
        if fields.get("identity") == "true":
            day = fields["time"]
        elif fields.get("temperature", "").isdigit():
            night = (fields["time"], int(fields["temperature"]))
    if night and day:
        return night[0], day, night[1]
    return None


def render_schedule(start: str, end: str, temp: int) -> str:
    return ("# Generated by omarchy-settings (night light schedule).\n"
            "# hyprsunset switches to the most recent profile by time of day.\n\n"
            f"profile {{\n    time = {end}\n    identity = true\n}}\n\n"
            f"profile {{\n    time = {start}\n    temperature = {temp}\n}}\n")


def valid_time(text: str) -> str | None:
    m = re.fullmatch(r"\s*(\d{1,2}):(\d{2})\s*", text)
    if not m or int(m.group(1)) > 23 or int(m.group(2)) > 59:
        return None
    return f"{int(m.group(1)):02d}:{m.group(2)}"


def write_schedule(start: str, end: str, temp: int, path: Path = HYPRSUNSET_CONF) -> None:
    """Writes the schedule; the first time, the file as it was is kept next to it."""
    backup = path.with_name(path.name + ".omarchy-settings.bak")
    if path.exists() and not backup.exists():
        shutil.copy2(path, backup)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_schedule(start, end, temp))


def restore_schedule(path: Path = HYPRSUNSET_CONF) -> bool:
    """Puts back the file from before the schedule (Omarchy's 'no tint' default). False if there's no backup."""
    backup = path.with_name(path.name + ".omarchy-settings.bak")
    if not backup.exists():
        return False
    shutil.copy2(backup, path)
    return True


# ------------------------------------------------------------------ power button
POWER_KEY = "XF86PowerOff"
POWER_ACTIONS = {  # action -> command; "menu" is Omarchy's default and "nothing" only unbinds
    "menu": "omarchy-menu toggle system",
    "lock": "omarchy-system-lock",
    "suspend": "systemctl suspend",
    "shutdown": "omarchy-system-shutdown",
    "nothing": None,
}


def render_extras(extras: dict) -> list[str]:
    """Lua lines for the generated file: power button and night light schedule autostart."""
    lines = []
    action = extras.get("power_button")
    if action in POWER_ACTIONS and action != "menu":
        lines += ["", "-- Power button", f"pcall(function() hl.unbind({core.lua(POWER_KEY)}) end)"]
        if POWER_ACTIONS[action]:
            lines.append(f"pcall(function() o.bind({core.lua(POWER_KEY)}, \"Power button\", "
                         f"{core.lua(POWER_ACTIONS[action])}, {{ locked = true }}) end)")
    if extras.get("nightlight_schedule"):
        lines += ["", "-- Night light schedule (~/.config/hypr/hyprsunset.conf)",
                  "pcall(function() o.launch_on_start(\"hyprsunset\") end)"]
    return lines
