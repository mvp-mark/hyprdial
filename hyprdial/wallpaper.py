"""Wallpaper on plain Hyprland (no GTK, testable), through hyprpaper.

Like idle.py: hyprpaper reads hyprlang, so the app writes its own ~/.config/hypr/hyprdial-paper.conf, starts
`hyprpaper -c` on it at login, and changes the wallpaper live with `hyprctl hyprpaper wallpaper`. A
hyprpaper.conf of the user's, or a hyprpaper this app didn't start, stays in charge.

    extras["wallpaper"] = {"path": "/…/a.jpg", "fit": "cover", "monitors": {"DP-1": "/…/b.png"}}
"""

from __future__ import annotations

import os
import re
import shlex
from pathlib import Path

from . import core

CONF = core.CONF_DIR / "hypr" / "hyprdial-paper.conf"
USER_CONF = core.CONF_DIR / "hypr" / "hyprpaper.conf"
FITS = ("cover", "contain", "tile", "fill")
IMAGES = (".jpg", ".jpeg", ".png", ".webp", ".jxl", ".bmp")


def available() -> bool:
    return core.have("hyprpaper")


def _running() -> list[tuple[str, str]]:
    found = []
    for line in core.out(["pgrep", "-a", "-x", "hyprpaper"]).splitlines():
        pid, _sep, cmdline = line.partition(" ")
        found.append((pid, cmdline))
    return found


def owner(user_conf=USER_CONF, conf=CONF) -> str:
    """'app' when this app runs hyprpaper (or nobody does), 'user' when the user's own config is in charge."""
    if user_conf.exists():
        return "user"
    return "user" if any(str(conf) not in cmdline for _pid, cmdline in _running()) else "app"


def settings(extras: dict) -> dict:
    saved = extras.get("wallpaper") if isinstance(extras.get("wallpaper"), dict) else {}
    monitors = saved.get("monitors") if isinstance(saved.get("monitors"), dict) else {}
    return {
        "path": str(saved.get("path") or ""),
        "fit": saved.get("fit") if saved.get("fit") in FITS else "cover",
        "monitors": {str(m): str(p) for m, p in monitors.items() if p},
    }


def problem(path: str) -> str | None:
    """Why an image can't be used, or None (the text is for the user)."""
    p = Path(path)
    if any(c in path for c in ",\n") or not p.is_absolute():
        return "path"
    if not p.is_file() or p.suffix.lower() not in IMAGES:
        return "image"
    return None


def render_conf(values: dict) -> str:
    lines = ["# Generated by Hyprdial (wallpaper). Manual edits will be overwritten.", "splash = false"]
    entries = [("", values["path"])] if values["path"] else []
    entries += sorted(values["monitors"].items())
    for monitor, path in entries:
        lines += [
            "",
            "wallpaper {",
            f"    monitor = {monitor}",
            f"    path = {path}",
            f"    fit_mode = {values['fit']}",
            "}",
        ]
    return "\n".join(lines) + "\n"


def write(values: dict, conf=CONF) -> None:
    conf.parent.mkdir(parents=True, exist_ok=True)
    tmp = conf.with_name(conf.name + ".tmp")
    tmp.write_text(render_conf(values))
    os.replace(tmp, conf)


def start_command(conf=CONF) -> str:
    return f"hyprpaper -c {shlex.quote(str(conf))}"


def render_extras(extras: dict) -> list[str]:
    values = settings(extras)
    if not (values["path"] or values["monitors"]) or not available() or owner() == "user":
        return []
    return ["", "-- Wallpaper (~/.config/hypr/hyprdial-paper.conf)", core.on_start_call(start_command())]


def apply(values: dict, monitors: list[str], conf=CONF) -> bool:
    """Shows the wallpaper now: through hyprpaper's IPC when this app's hyprpaper runs, else by starting it."""
    if not any(str(conf) in cmdline for _pid, cmdline in _running()):
        return core.spawn(["hyprpaper", "-c", str(conf)])
    ok = True
    for monitor in monitors:
        path = values["monitors"].get(monitor) or values["path"]
        if path:
            r = core.run(["hyprctl", "hyprpaper", "wallpaper", f"{monitor}, {path}, {values['fit']}"])
            ok = ok and bool(r and r.returncode == 0 and not re.search(r"error|invalid", r.stdout, re.I))
    return ok
