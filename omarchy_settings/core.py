"""GTK-free core: running commands and editing the Hyprland configs.

Strategy: the user's and Omarchy's files are left alone. Settings live in ~/.config/hypr/omarchy-settings.lua
(generated) and a single `require(...)` line is inserted into hyprland.lua, after the user's files, so these
values have the last word.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import threading
import time
from pathlib import Path

HOME = Path.home()
CONF_DIR = HOME / ".config"
HYPR_MAIN = CONF_DIR / "hypr" / "hyprland.lua"
HYPR_MANAGED = CONF_DIR / "hypr" / "omarchy-settings.lua"
STATE_FILE = CONF_DIR / "omarchy-settings" / "state.json"
REQUIRE_LINE = 'require("hypr.omarchy-settings")'
TOGGLES_LINE = 'require("default.hypr.toggles")'
HEADER = (
    "-- Generated by omarchy-settings. Manual edits will be overwritten.\n"
    "-- To return to the defaults, delete this file or use the app's restore buttons.\n"
)


# --------------------------------------------------------------------------- processos
def have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def run(args: list[str], timeout: float = 10) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(args, capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return None


def out(args: list[str], timeout: float = 10) -> str:
    r = run(args, timeout)
    return r.stdout.strip() if r and r.returncode == 0 else ""


def spawn(args: list[str]) -> bool:
    """Starts a process detached from the window."""
    try:
        subprocess.Popen(
            args,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
        return True
    except OSError:
        return False


def launch_tui(cmd: str) -> bool:
    if have("omarchy-launch-tui"):
        return spawn(["omarchy-launch-tui", cmd])
    if have("xdg-terminal-exec"):
        return spawn(["xdg-terminal-exec", cmd])
    return spawn(["alacritty", "-e", cmd])


def open_in_editor(path: Path) -> bool:
    if have("omarchy-launch-editor"):
        return spawn(["omarchy-launch-editor", str(path)])
    return spawn(["xdg-open", str(path)])


# --------------------------------------------------------------------------- Hyprland
def live_option(key: str):
    """Current value of an option in the running Hyprland (or None)."""
    raw = out(["hyprctl", "getoption", key, "-j"])
    try:
        data = json.loads(raw)
    except (ValueError, TypeError):
        return None
    if not isinstance(data, dict):
        return None
    for field in ("bool", "int", "float"):
        if field in data:
            return data[field]
    if "str" in data:
        return "" if data["str"] == "[[EMPTY]]" else data["str"]
    for field in ("css", "custom"):  # ex.: gaps_in => "5 5 5 5"
        value = data.get(field)
        if isinstance(value, str) and value.split():
            return value.split()[0]
    return None


def fmt(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.6f}".rstrip("0").rstrip(".") if value % 1 else str(int(value))
    return str(value)


def lua(value) -> str:
    """Lua literal for an already typed Python value (bool, number or string)."""
    if isinstance(value, (bool, int, float)):
        return fmt(value)
    text = str(value)
    if any(ord(c) < 32 for c in text):
        raise ValueError(f"invalid value: {text!r}")
    return json.dumps(text, ensure_ascii=False)


def option_lua(text: str) -> str:
    """Options are stored as text; recover bool/number before turning them into Lua."""
    if text in ("true", "false"):
        return text
    try:
        float(text)
        return text
    except ValueError:
        return lua(text)


def lua_key(name: str) -> str:
    """In the Lua API, hyphenated options (e.g. hyprctl's 'tap-to-click') use underscores."""
    return name.replace("-", "_")


def config_call(values: dict[str, str]) -> str:
    """Turns {'decoration:blur:enabled': 'true', ...} into hl.config({ ... })."""
    tree: dict = {}
    for key in sorted(values):
        *path, leaf = key.split(":")
        node = tree
        for part in path:
            node = node.setdefault(part, {})
        node[leaf] = values[key]

    lines = ["hl.config({"]

    def emit(node: dict, depth: int) -> None:
        pad = "  " * depth
        for k, v in node.items():
            if isinstance(v, dict):
                lines.append(f"{pad}{lua_key(k)} = {{")
                emit(v, depth + 1)
                lines.append(f"{pad}}},")
            else:
                lines.append(f"{pad}{lua_key(k)} = {option_lua(v)},")

    emit(tree, 1)
    lines.append("})")
    return "\n".join(lines)


MONITOR_FIELDS = ("output", "disabled", "mode", "position", "scale", "transform", "vrr", "mirror", "bitdepth")


def monitor_call(rule: dict) -> str:
    fields = ", ".join(f"{k} = {lua(rule[k])}" for k in MONITOR_FIELDS if k in rule)
    return f"hl.monitor({{ {fields} }})"


def render(
    values: dict[str, str], monitors: dict[str, dict], bindings: dict | None = None, extras: dict | None = None
) -> str:
    from . import accessibility, autostart, keybinds, power  # imported here: they depend on this module

    parts = [HEADER]
    if values:
        parts.append(config_call(values))
    parts.extend(monitor_call(monitors[name]) for name in sorted(monitors))
    parts.extend(keybinds.render(bindings or {}))
    parts.extend(power.render_extras(extras or {}))
    parts.extend(autostart.render_extras(extras or {}))
    parts.extend(accessibility.render_extras(extras or {}))
    return "\n".join(parts) + "\n"


def home_path(path: Path) -> str:
    """~/.config/... for showing a path."""
    return str(path).replace(str(HOME), "~", 1)


def on_start_call(command: str) -> str:
    """Lua line that starts a desktop app when Hyprland starts."""
    from . import host

    if host.is_omarchy():
        return f"pcall(function() o.launch_on_start({lua(command)}) end)"
    start = f"hl.exec_cmd({lua(host.launch(command))})"
    return f'pcall(function() hl.on("hyprland.start", function() {start} end) end)'


def bind_call(keys: str, description: str, action: str, options: str = "") -> str:
    """Lua line for a shortcut. action is a Lua expression: on Omarchy anything o.bind takes (a command string,
    { launch = ... }, a dispatcher); elsewhere a dispatcher (hl.dsp....) or a command string. options are the
    fields of the options table ("locked = true")."""
    from . import host

    if host.is_omarchy():
        extra = f", {{ {options} }}" if options else ""
        return f"pcall(function() o.bind({lua(keys)}, {lua(description)}, {action}{extra}) end)"
    named = re.search(r"\bdescription\s*=", options)  # an hl.bind from the user's files keeps its own
    fields = ", ".join(f for f in ("" if named else f"description = {lua(description)}", options) if f)
    return f"pcall(function() hl.bind({lua(keys)}, {native_dispatcher(action)}, {{ {fields} }}) end)"


def native_dispatcher(action: str) -> str:
    """A command string becomes hl.dsp.exec_cmd(...); a dispatcher expression is kept."""
    text = action.strip()
    return f"hl.dsp.exec_cmd({text})" if text[:1] in "\"'" else text


def list_monitors() -> list[dict]:
    """Connected displays (disabled ones included) according to the running Hyprland."""
    try:
        data = json.loads(out(["hyprctl", "monitors", "all", "-j"]))
    except (ValueError, TypeError):
        return []
    return data if isinstance(data, list) else []


def live_rule(mon: dict) -> dict:
    """hl.monitor rule equivalent to a display's current state."""
    rule = {
        "output": mon["name"],
        "mode": f"{mon['width']}x{mon['height']}@{mon['refreshRate']:.2f}",
        "position": f"{mon['x']}x{mon['y']}",
        "scale": mon["scale"],
        "transform": mon.get("transform", 0),
    }
    if mon.get("vrr"):
        rule["vrr"] = 1
    if mon.get("mirrorOf") not in (None, "", "none"):
        rule["mirror"] = mon["mirrorOf"]
    if mon.get("disabled"):
        rule["disabled"] = True
    return rule


class HyprStore:
    """Keeps Hyprland settings, applies them live (hyprctl eval) and persists them to a file.

    read_only (Hyprland not running, too old, or still on hyprland.conf) keeps changes in memory only: nothing is
    written, evaluated or reloaded."""

    DEBOUNCE = 0.25
    read_only = False

    def __init__(self, managed: Path = HYPR_MANAGED, main: Path = HYPR_MAIN, state: Path = STATE_FILE):
        self.managed, self.main, self.state_file = managed, main, state
        self.values, self.monitors, self.bindings, self.extras = self._load()
        self._pending: dict[str, str | None] = {}
        self._pending_monitors: dict[str, dict | None] = {}
        self._lock = threading.Lock()
        self._timer: threading.Timer | None = None

    # -- estado
    def _load(self) -> tuple[dict[str, str], dict[str, dict], dict, dict]:
        empty = {"overrides": {}, "custom": []}
        try:
            data = json.loads(self.state_file.read_text())
            values = {str(k): str(v) for k, v in data.get("hypr", {}).items()}
            monitors = {str(k): dict(v) for k, v in data.get("monitors", {}).items()}
            bindings = data.get("bindings") if isinstance(data.get("bindings"), dict) else empty
            extras = data.get("extras") if isinstance(data.get("extras"), dict) else {}
            return values, monitors, {**empty, **bindings}, extras
        except (OSError, ValueError, AttributeError, TypeError):
            return {}, {}, empty, {}

    # reads include what is still queued, so back-to-back changes don't overwrite each other
    def get(self, key: str) -> str | None:
        with self._lock:
            if key in self._pending:
                return self._pending[key]
        return self.values.get(key)

    def set(self, key: str, value) -> None:
        self._queue(self._pending, key, fmt(value))

    def unset(self, key: str) -> None:
        self._queue(self._pending, key, None)

    def get_monitor(self, output: str) -> dict | None:
        with self._lock:
            rule = self._pending_monitors.get(output, self.monitors.get(output))
        return dict(rule) if rule else None

    def set_monitor(self, rule: dict) -> None:
        self._queue(self._pending_monitors, rule["output"], dict(rule))

    def unset_monitor(self, output: str) -> None:
        self._queue(self._pending_monitors, output, None)

    def reset_options(self) -> None:
        """Removes only the Hyprland options; displays and shortcuts have their own restore."""
        for key in list(self.values):
            self.unset(key)

    def apply_bindings(self, bindings: dict) -> None:
        """Writes the shortcuts and reloads Hyprland right away (call it off the UI thread)."""
        self.flush()
        with self._lock:
            self.bindings = bindings
        self.save()
        self._reload()

    def set_extra(self, key: str, value, reload: bool = True) -> None:
        """Power and night light settings: written (and reloaded) right away; call it off the UI thread."""
        self.flush()
        with self._lock:
            if value is None:
                self.extras.pop(key, None)
            else:
                self.extras[key] = value
        self.save()
        if reload:
            self._reload()

    def reset_all(self) -> tuple[dict, Path | None]:
        """Back to plain Omarchy: empties the generated file and reloads (call it off the UI thread).

        Returns what was there, for restore(), and the backup copy of the generated file.
        """
        self.flush()
        with self._lock:
            previous = {
                "values": self.values,
                "monitors": self.monitors,
                "bindings": self.bindings,
                "extras": self.extras,
            }
            self.values, self.monitors, self.bindings, self.extras = {}, {}, {"overrides": {}, "custom": []}, {}
        backup = None
        if self.managed.exists() and not self.read_only:
            backup = self.managed.with_name(f"{self.managed.name}.{time.strftime('%Y%m%d-%H%M%S')}.bak")
            shutil.copy2(self.managed, backup)
        self.save()
        self._reload()
        return previous, backup

    def restore(self, previous: dict) -> None:
        """Undoes reset_all()."""
        self.flush()
        with self._lock:
            self.values, self.monitors = previous["values"], previous["monitors"]
            self.bindings, self.extras = previous["bindings"], previous["extras"]
        self.save()
        self._reload()

    def _queue(self, pending: dict, key: str, value) -> None:
        with self._lock:
            pending[key] = value
        self._schedule()

    def _schedule(self) -> None:
        with self._lock:
            if self._timer:
                self._timer.cancel()
            self._timer = threading.Timer(self.DEBOUNCE, self.flush)
            self._timer.daemon = True
            self._timer.start()

    # -- applying
    def flush(self) -> None:
        with self._lock:
            pending, self._pending = self._pending, {}
            monitors, self._pending_monitors = self._pending_monitors, {}
        if not pending and not monitors:
            return
        needs_reload = False
        changed: dict[str, str] = {}
        for key, value in pending.items():
            if value is None:
                self.values.pop(key, None)
                needs_reload = True  # there is no live 'unset': reload the config
            else:
                self.values[key] = changed[key] = value
        live = [config_call(changed)] if changed else []
        for output, rule in monitors.items():
            if rule is None:
                self.monitors.pop(output, None)
                needs_reload = True
            else:
                self.monitors[output] = rule
                live.append(monitor_call(rule))
        self.save()
        if self.read_only:
            return
        if needs_reload:
            self._reload()
        else:
            for code in live:
                run(["hyprctl", "eval", code])

    def _reload(self) -> None:
        if not self.read_only:
            run(["hyprctl", "reload"])

    def save(self) -> None:
        if self.read_only:
            return
        self.managed.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.managed.with_suffix(".tmp")
        tmp.write_text(render(self.values, self.monitors, self.bindings, self.extras))
        os.replace(tmp, self.managed)
        self.state_file.parent.mkdir(parents=True, exist_ok=True)
        self.state_file.write_text(
            json.dumps(
                {"hypr": self.values, "monitors": self.monitors, "bindings": self.bindings, "extras": self.extras},
                indent=2,
                ensure_ascii=False,
            )
        )
        self.ensure_required()

    def ensure_required(self) -> None:
        """Loads the generated file after the user's files but before Omarchy's toggles."""
        if not self.main.exists():
            return
        text = self.main.read_text()
        if REQUIRE_LINE in text:
            return
        backup = self.main.with_name(self.main.name + ".omarchy-settings.bak")
        if not backup.exists():
            shutil.copy2(self.main, backup)
        block = f"-- Added by omarchy-settings\n{REQUIRE_LINE}\n"
        lines = text.splitlines(keepends=True)
        for i, line in enumerate(lines):
            if line.strip() == TOGGLES_LINE:
                while i > 0 and lines[i - 1].lstrip().startswith("--"):
                    i -= 1  # keep the comment next to the line it describes
                lines.insert(i, block + "\n")
                break
        else:
            sep = "" if text.endswith("\n") else "\n"
            lines.append(f"{sep}\n{block}")
        self.main.write_text("".join(lines))
