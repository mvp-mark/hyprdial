"""Lock and idle on plain Hyprland (no GTK, testable), through hypridle.

hypridle reads hyprlang, not Lua, so the app writes its own ~/.config/hypr/hyprdial-idle.conf and the generated
file starts `hypridle -c` on it at login. When the user has a hypridle.conf of their own, or a hypridle not
started by this app is running, theirs is in charge and the app only says so.

    extras["idle"] = {"dim": 150, "lock": 300, "screen_off": 330, "suspend": 1800}   seconds; 0 = never
"""

from __future__ import annotations

import os
import re
import shlex

from . import core

CONF = core.CONF_DIR / "hypr" / "hyprdial-idle.conf"
USER_CONF = core.CONF_DIR / "hypr" / "hypridle.conf"
STEPS = ("dim", "lock", "screen_off", "suspend")
DEFAULTS = {"dim": 150, "lock": 300, "screen_off": 330, "suspend": 0}
DPMS = "hyprctl dispatch 'hl.dsp.dpms({{ action = \"{}\" }})'"


def available() -> bool:
    return core.have("hypridle")


def ours(cmdline: str, conf=CONF) -> bool:
    return str(conf) in cmdline


def running() -> list[str]:
    """Command lines of the running hypridle processes."""
    return [
        line.split(" ", 1)[1] if " " in line else ""
        for line in core.out(["pgrep", "-a", "-x", "hypridle"]).splitlines()
    ]


def owner(user_conf=USER_CONF, conf=CONF) -> str:
    """'app' when this app runs hypridle (or nobody does), 'user' when the user's own config is in charge."""
    if user_conf.exists():
        return "user"
    return "user" if any(not ours(c, conf) for c in running()) else "app"


def settings(extras: dict) -> dict[str, int]:
    saved = extras.get("idle") if isinstance(extras.get("idle"), dict) else {}
    return {k: int(saved.get(k, DEFAULTS[k])) if str(saved.get(k, "")).isdigit() else DEFAULTS[k] for k in STEPS}


def lock_command() -> str:
    return "pidof hyprlock || hyprlock" if core.have("hyprlock") else "loginctl lock-session"


def render_conf(values: dict[str, int]) -> str:
    lines = [
        "# Generated by Hyprdial (lock and idle). Manual edits will be overwritten.",
        "general {",
        f"    lock_cmd = {lock_command()}",
        "    before_sleep_cmd = loginctl lock-session",
        f"    after_sleep_cmd = {DPMS.format('enable')}",
        "}",
    ]

    def listener(timeout: int, on_timeout: str, on_resume: str = "") -> None:
        lines.extend(["", "listener {", f"    timeout = {timeout}", f"    on-timeout = {on_timeout}"])
        if on_resume:
            lines.append(f"    on-resume = {on_resume}")
        lines.append("}")

    if values["dim"] and core.have("brightnessctl"):
        listener(values["dim"], "brightnessctl -s set 10", "brightnessctl -r")
    if values["lock"]:
        listener(values["lock"], "loginctl lock-session")
    if values["screen_off"]:
        listener(values["screen_off"], DPMS.format("disable"), DPMS.format("enable"))
    if values["suspend"]:
        listener(values["suspend"], "systemctl suspend")
    return "\n".join(lines) + "\n"


def write(values: dict[str, int], conf=CONF) -> None:
    conf.parent.mkdir(parents=True, exist_ok=True)
    tmp = conf.with_name(conf.name + ".tmp")
    tmp.write_text(render_conf(values))
    os.replace(tmp, conf)


def start_command(conf=CONF) -> str:
    return f"hypridle -c {shlex.quote(str(conf))}"


def render_extras(extras: dict) -> list[str]:
    """Starts this app's hypridle at login; nothing when the user runs their own."""
    if not extras.get("idle") or not available() or owner() == "user":
        return []
    return ["", "-- Lock and idle (~/.config/hypr/hyprdial-idle.conf)", core.on_start_call(start_command())]


def restart(conf=CONF) -> None:
    """Applies new times now: hypridle doesn't reload its config, so this app's instance is restarted."""
    for line in core.out(["pgrep", "-a", "-x", "hypridle"]).splitlines():
        pid, _sep, cmdline = line.partition(" ")
        if ours(cmdline, conf) and re.fullmatch(r"\d+", pid):
            core.run(["kill", pid])
    core.spawn(["hypridle", "-c", str(conf)])
