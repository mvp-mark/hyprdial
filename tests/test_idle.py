from hyprdial import idle


def test_settings_defaults_and_bad_values():
    assert idle.settings({}) == idle.DEFAULTS
    assert idle.settings({"idle": {"lock": 600, "suspend": "x"}}) == {**idle.DEFAULTS, "lock": 600}


def test_render_conf(commands):
    commands.have = {"hyprlock", "brightnessctl"}
    text = idle.render_conf({"dim": 120, "lock": 300, "screen_off": 0, "suspend": 1800})
    assert "lock_cmd = pidof hyprlock || hyprlock" in text
    assert "timeout = 120\n    on-timeout = brightnessctl -s set 10\n    on-resume = brightnessctl -r" in text
    assert "timeout = 300\n    on-timeout = loginctl lock-session" in text
    assert "dpms" not in text.split("listener")[-1] and "timeout = 1800\n    on-timeout = systemctl suspend" in text
    commands.have = set()
    text = idle.render_conf({"dim": 120, "lock": 0, "screen_off": 330, "suspend": 0})
    assert "lock_cmd = loginctl lock-session" in text and "brightnessctl" not in text
    assert "on-timeout = hyprctl dispatch 'hl.dsp.dpms({ action = \"disable\" })'" in text


def test_owner(commands, tmp_path):
    conf, user = tmp_path / "hyprdial-idle.conf", tmp_path / "hypridle.conf"
    assert idle.owner(user, conf) == "app"
    commands.answers["pgrep -a -x hypridle"] = f"42 hypridle -c {conf}"
    assert idle.owner(user, conf) == "app"
    commands.answers["pgrep -a -x hypridle"] = "43 hypridle"
    assert idle.owner(user, conf) == "user"
    commands.answers["pgrep -a -x hypridle"] = ""
    user.write_text("")
    assert idle.owner(user, conf) == "user"


def test_render_extras_starts_only_this_apps_hypridle(commands, plain_hyprland, monkeypatch, tmp_path):
    monkeypatch.setattr(idle, "USER_CONF", tmp_path / "none")
    assert idle.render_extras({"idle": {"lock": 300}}) == []  # hypridle not installed
    commands.have = {"hypridle"}
    assert idle.render_extras({"idle": {"lock": 300}})[-1] == (
        f'pcall(function() hl.on("hyprland.start", function() hl.exec_cmd("hypridle -c {idle.CONF}") end) end)'
    )
    assert idle.render_extras({}) == []


def test_restart_kills_only_this_apps_hypridle(commands, tmp_path):
    conf = tmp_path / "hyprdial-idle.conf"
    commands.answers["pgrep -a -x hypridle"] = f"42 hypridle -c {conf}\n43 hypridle"
    idle.restart(conf)
    assert commands.calls == [["kill", "42"]] and commands.spawned == [["hypridle", "-c", str(conf)]]


def test_write(tmp_path):
    conf = tmp_path / "x.conf"
    idle.write(idle.DEFAULTS, conf)
    assert conf.read_text().startswith("# Generated by Hyprdial")
