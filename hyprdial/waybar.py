"""Waybar as an alternative to the Omarchy shell bar (no GTK, testable).

Current Omarchy doesn't manage Waybar. This module creates a starter configuration in ~/.config/waybar, makes
its style follow the Omarchy theme and runs Waybar instead of the shell bar:

- colors: a user template (~/.config/omarchy/themed/waybar.css.tpl) that Omarchy itself renders into
  ~/.local/state/omarchy/current/theme/waybar.css on every theme change; style.css imports it;
- Omarchy hooks: theme-set.d reloads Waybar after a theme change and post-boot.d starts it at login.
"""

from __future__ import annotations

import re
import shutil
import tomllib
from pathlib import Path

from . import core

CONFIG_DIR = core.CONF_DIR / "waybar"
CONFIG = CONFIG_DIR / "config.jsonc"
STYLE = CONFIG_DIR / "style.css"
THEME_DIR = core.HOME / ".local/state/omarchy/current/theme"
TEMPLATE = core.CONF_DIR / "omarchy" / "themed" / "waybar.css.tpl"
RENDERED = THEME_DIR / "waybar.css"
HOOKS_DIR = core.CONF_DIR / "omarchy" / "hooks"
HOOK_NAME = "omarchy-settings-waybar"  # the app's old name: hooks already installed keep working
THEME_HOOK = HOOKS_DIR / "theme-set.d" / HOOK_NAME
BOOT_HOOK = HOOKS_DIR / "post-boot.d" / HOOK_NAME
BAR_OFF_FLAG = core.HOME / ".local/state/omarchy/toggles/bar-off"

POSITIONS = ("top", "bottom", "left", "right")
POSITION_RE = re.compile(r'("position"\s*:\s*")(top|bottom|left|right)(")')

TEMPLATE_CSS = """/* Generated by Hyprdial: the current theme's colors for Waybar. */
@define-color background {{ background }};
@define-color foreground {{ foreground }};
@define-color accent {{ accent }};
@define-color muted {{ muted }};
@define-color red {{ red }};
@define-color yellow {{ yellow }};
@define-color green {{ green }};
"""

