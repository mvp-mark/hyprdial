THEME_HOOK_SCRIPT = """#!/bin/bash
# Generated by Hyprdial: reloads Waybar to apply the new theme's colors.
pkill -SIGUSR2 -x waybar || true
"""

BOOT_HOOK_SCRIPT = """#!/bin/bash
# Generated by Hyprdial: starts Waybar instead of the Omarchy bar.
pgrep -x waybar >/dev/null || setsid uwsm-app -- waybar >/dev/null 2>&1 &
"""


# ------------------------------------------------------------------ state
def installed() -> bool:
    return core.have("waybar")


def running() -> bool:
    r = core.run(["pgrep", "-x", "waybar"])
    return bool(r and r.returncode == 0)


def enabled() -> bool:
    """Waybar was chosen instead of the Omarchy bar (starts at login)."""
    return BOOT_HOOK.exists()


def has_config() -> bool:
    return CONFIG.exists()


# ------------------------------------------------------------------ theme colors
def render(template: str, colors: dict) -> str:
    return re.sub(r"\{\{\s*(\w+)\s*\}\}", lambda m: str(colors.get(m.group(1), m.group(0))), template)


def render_theme_css() -> bool:
    """Renders waybar.css for the current theme now; on later theme changes Omarchy does it by itself."""
    try:
        colors = tomllib.loads((THEME_DIR / "colors.toml").read_text())
        RENDERED.write_text(render(TEMPLATE.read_text(), colors))
        return True
    except (OSError, tomllib.TOMLDecodeError):
        return False


# ------------------------------------------------------------------ files
def _write_hook(path: Path, script: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(script)
    path.chmod(0o755)


def ensure_config() -> None:
    """Creates the config, style, color template and theme hook, without overwriting what already exists."""
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    if not CONFIG.exists():
        CONFIG.write_text(STARTER_CONFIG)
    if not STYLE.exists():
        STYLE.write_text(starter_style())
    if not TEMPLATE.exists():
        TEMPLATE.parent.mkdir(parents=True, exist_ok=True)
        TEMPLATE.write_text(TEMPLATE_CSS)
    _write_hook(THEME_HOOK, THEME_HOOK_SCRIPT)
    render_theme_css()


def reset_config() -> None:
    """Resets config and style to the starter ones, keeping the current files with a .hyprdial.bak suffix."""
    for path in (CONFIG, STYLE):
        if path.exists():
            shutil.copy2(path, path.with_name(path.name + ".hyprdial.bak"))
            path.unlink()
    ensure_config()


def read_position() -> str:
    try:
        m = POSITION_RE.search(CONFIG.read_text())
    except OSError:
        return "top"
    return m.group(2) if m else "top"


def write_position(position: str) -> bool:
    if position not in POSITIONS:
        raise ValueError(position)
    try:
        text = CONFIG.read_text()
    except OSError:
        return False
    if not POSITION_RE.search(text):
        return False
    CONFIG.write_text(POSITION_RE.sub(rf"\g<1>{position}\g<3>", text, count=1))
    return True


# ------------------------------------------------------------------ process
def start() -> bool:
    if running():
        return True
    prefix = ["uwsm-app", "--"] if core.have("uwsm-app") else []
    return core.spawn(prefix + ["waybar"])


def stop() -> None:
    core.run(["pkill", "-x", "waybar"])


def reload() -> None:
    """Waybar re-reads its config and style on SIGUSR2."""
    core.run(["pkill", "-SIGUSR2", "-x", "waybar"])


def set_enabled(on: bool) -> None:
    """Runs Waybar instead of the Omarchy bar (and at login), or goes back to the Omarchy bar."""
    if on:
        ensure_config()
        _write_hook(BOOT_HOOK, BOOT_HOOK_SCRIPT)
        start()
        core.run(["omarchy-toggle-bar", "on"])  # sets the bar-off flag: hides the shell bar
    else:
        BOOT_HOOK.unlink(missing_ok=True)
        stop()
        core.run(["omarchy-toggle-bar", "off"])  # shows the shell bar again
